-- Đơn đặt chỗ (tour, khách sạn, vé máy bay). Phần chung ở `bookings`, chi tiết theo loại ở bảng riêng (1-1 theo
-- booking_id). Thanh toán lưu RIÊNG ở `payments` (tài liệu MVP: trạng thái đơn và trạng thái thanh toán không gộp).
-- Giá được CHỐT vào đơn lúc đặt: đổi giá danh mục không làm đổi đơn cũ.

CREATE TABLE bookings (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- "GT" + 6 ký tự (bỏ ký tự dễ đọc nhầm 0/O, 1/I/L), cũng là nội dung chuyển khoản.
    code          varchar(8)   NOT NULL,
    kind          varchar(10)  NOT NULL,
    -- Chủ đơn: id người dùng (claim `sub` của JWT), KHÔNG theo email.
    user_id       uuid         NOT NULL,
    status        varchar(10)  NOT NULL,
    total_amount  bigint       NOT NULL,
    contact_name  varchar(100) NOT NULL,
    contact_email varchar(254) NOT NULL,
    contact_phone varchar(30)  NOT NULL,
    note          varchar(500),
    created_at    timestamptz  NOT NULL,
    confirmed_at  timestamptz,
    cancelled_at  timestamptz,
    CONSTRAINT uq_bookings_code UNIQUE (code),
    CONSTRAINT ck_bookings_code_format CHECK (code ~ '^GT[2-9A-HJKMNP-Z]{6}$'),
    CONSTRAINT ck_bookings_kind CHECK (kind IN ('TOUR', 'HOTEL', 'FLIGHT')),
    CONSTRAINT fk_bookings_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_bookings_status CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED')),
    CONSTRAINT ck_bookings_total_amount CHECK (total_amount >= 0)
);

-- "Đơn của tôi", mới nhất trước.
CREATE INDEX idx_bookings_user_created ON bookings (user_id, created_at DESC, id DESC);

CREATE TABLE payments (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id bigint      NOT NULL,
    method     varchar(20) NOT NULL,
    amount     bigint      NOT NULL,
    status     varchar(10) NOT NULL,
    paid_at    timestamptz,
    CONSTRAINT uq_payments_booking UNIQUE (booking_id),
    CONSTRAINT fk_payments_booking FOREIGN KEY (booking_id) REFERENCES bookings (id) ON DELETE CASCADE,
    CONSTRAINT ck_payments_method CHECK (method IN ('BANK_TRANSFER')),
    CONSTRAINT ck_payments_amount CHECK (amount >= 0),
    CONSTRAINT ck_payments_status CHECK (status IN ('UNPAID', 'PAID', 'CANCELLED'))
);

-- Số chỗ của đơn tour được giữ ngay trong tour_departures.booked_seats (cập nhật có điều kiện).
CREATE TABLE tour_bookings (
    booking_id   bigint  PRIMARY KEY,
    departure_id bigint  NOT NULL,
    guests       integer NOT NULL,
    -- Giá mỗi khách tại thời điểm đặt, VND.
    unit_price   bigint  NOT NULL,
    CONSTRAINT fk_tour_bookings_booking FOREIGN KEY (booking_id) REFERENCES bookings (id) ON DELETE CASCADE,
    CONSTRAINT fk_tour_bookings_departure FOREIGN KEY (departure_id) REFERENCES tour_departures (id),
    CONSTRAINT ck_tour_bookings_guests CHECK (guests > 0),
    CONSTRAINT ck_tour_bookings_unit_price CHECK (unit_price >= 0)
);

CREATE INDEX idx_tour_bookings_departure_id ON tour_bookings (departure_id);

CREATE TABLE hotel_bookings (
    booking_id      bigint       PRIMARY KEY,
    room_type_id    bigint       NOT NULL,
    check_in        date         NOT NULL,
    check_out       date         NOT NULL,
    nights          integer      NOT NULL,
    rooms           integer      NOT NULL,
    guests          integer      NOT NULL,
    -- Giá MỘT phòng MỘT đêm tại thời điểm đặt, VND.
    price_per_night bigint       NOT NULL,
    -- Người nhận phòng (xuất trình giấy tờ khi nhận phòng), có thể khác người liên hệ.
    guest_name      varchar(100) NOT NULL,
    CONSTRAINT fk_hotel_bookings_booking FOREIGN KEY (booking_id) REFERENCES bookings (id) ON DELETE CASCADE,
    CONSTRAINT fk_hotel_bookings_room_type FOREIGN KEY (room_type_id) REFERENCES hotel_room_types (id),
    CONSTRAINT ck_hotel_bookings_dates CHECK (check_out > check_in AND nights > 0),
    CONSTRAINT ck_hotel_bookings_rooms CHECK (rooms > 0 AND guests >= rooms),
    CONSTRAINT ck_hotel_bookings_price CHECK (price_per_night >= 0)
);

-- Đếm phòng đã đặt của một loại phòng trong một khoảng ngày.
CREATE INDEX idx_hotel_bookings_room_dates ON hotel_bookings (room_type_id, check_in, check_out);

CREATE TABLE flight_bookings (
    booking_id bigint      PRIMARY KEY,
    cabin      varchar(20) NOT NULL,
    CONSTRAINT fk_flight_bookings_booking FOREIGN KEY (booking_id) REFERENCES bookings (id) ON DELETE CASCADE,
    CONSTRAINT ck_flight_bookings_cabin CHECK (cabin IN ('ECONOMY', 'PREMIUM_ECONOMY', 'BUSINESS', 'FIRST'))
);

CREATE TABLE flight_booking_segments (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id    bigint  NOT NULL,
    -- 0 = chiều đi, 1 = chiều về.
    segment_index integer NOT NULL,
    schedule_id   bigint  NOT NULL,
    flight_date   date    NOT NULL,
    -- Giá vé MỘT hành khách mỗi loại tại thời điểm đặt, VND.
    adult_fare    bigint  NOT NULL,
    child_fare    bigint  NOT NULL,
    infant_fare   bigint  NOT NULL,
    CONSTRAINT uq_flight_booking_segments_index UNIQUE (booking_id, segment_index),
    CONSTRAINT fk_flight_booking_segments_booking FOREIGN KEY (booking_id)
        REFERENCES flight_bookings (booking_id) ON DELETE CASCADE,
    CONSTRAINT fk_flight_booking_segments_schedule FOREIGN KEY (schedule_id) REFERENCES flight_schedules (id),
    CONSTRAINT ck_flight_booking_segments_index CHECK (segment_index IN (0, 1)),
    CONSTRAINT ck_flight_booking_segments_fares CHECK (adult_fare >= 0 AND child_fare >= 0 AND infant_fare >= 0)
);

-- Đếm ghế đã bán của một lịch bay trong một ngày.
CREATE INDEX idx_flight_booking_segments_schedule_date ON flight_booking_segments (schedule_id, flight_date);

-- Người đi tour và hành khách bay. (Đơn khách sạn chỉ có người nhận phòng, lưu ở hotel_bookings.)
CREATE TABLE booking_travelers (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id     bigint       NOT NULL,
    -- Thứ tự khách nhập trong form.
    traveler_index integer      NOT NULL,
    -- Chỉ đơn vé máy bay có loại hành khách; đơn tour để trống.
    passenger_type varchar(10),
    full_name      varchar(100) NOT NULL,
    date_of_birth  date,
    CONSTRAINT uq_booking_travelers_index UNIQUE (booking_id, traveler_index),
    CONSTRAINT fk_booking_travelers_booking FOREIGN KEY (booking_id) REFERENCES bookings (id) ON DELETE CASCADE,
    CONSTRAINT ck_booking_travelers_type CHECK (
        passenger_type IS NULL OR passenger_type IN ('ADULT', 'CHILD', 'INFANT'))
);
