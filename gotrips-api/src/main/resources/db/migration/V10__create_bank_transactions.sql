-- Thanh toán chuyển khoản tự động: SePay theo dõi tài khoản nhận và gọi webhook mỗi khi có tiền vào. Mỗi giao dịch
-- được lưu lại (kể cả giao dịch không khớp đơn nào) để nhân viên đối chiếu, gắn đơn thủ công hoặc hoàn tiền.

-- Tổng tiền của các giao dịch đã tính vào khoản cần thu của đơn (khách có thể chuyển nhiều lần). Phần chuyển thừa
-- KHÔNG cộng vào đây (nằm ở bank_transactions), nên received_amount không bao giờ vượt amount.
ALTER TABLE payments ADD COLUMN received_amount bigint NOT NULL DEFAULT 0;
ALTER TABLE payments ADD CONSTRAINT ck_payments_received_amount
    CHECK (received_amount >= 0 AND received_amount <= amount);

CREATE TABLE bank_transactions (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- id giao dịch của SePay: không đổi qua các lần SePay gửi lại, nên là khoá chống ghi nhận trùng.
    sepay_id        bigint       NOT NULL,
    gateway         varchar(100) NOT NULL,
    account_number  varchar(50)  NOT NULL,
    amount          bigint       NOT NULL,
    -- Nội dung chuyển khoản nguyên văn từ ngân hàng (thường có tên người chuyển).
    content         text         NOT NULL,
    reference_code  varchar(255),
    -- Thời điểm ngân hàng ghi nhận giao dịch và thời điểm API nhận webhook.
    transaction_at  timestamptz  NOT NULL,
    received_at     timestamptz  NOT NULL,
    -- Đơn được gắn (tự động theo mã đơn trong nội dung, hoặc nhân viên gắn tay).
    booking_id      bigint,
    -- Phần tiền đã cộng vào payments.received_amount của đơn; phần còn lại (amount - applied_amount) cần xử lý.
    applied_amount  bigint       NOT NULL,
    outcome         varchar(20)  NOT NULL,
    -- Nhân viên gắn giao dịch vào đơn (NULL = hệ thống tự gắn hoặc chưa gắn).
    assigned_by     uuid,
    assigned_at     timestamptz,
    -- Nhân viên đánh dấu đã xử lý phần tiền lệch (hoàn tiền, giao dịch không liên quan...).
    resolved_by     uuid,
    resolved_at     timestamptz,
    resolution_note varchar(500),
    CONSTRAINT uq_bank_transactions_sepay_id UNIQUE (sepay_id),
    -- Không cascade: bản ghi tiền vào phải còn dù dữ liệu khác thay đổi.
    CONSTRAINT fk_bank_transactions_booking FOREIGN KEY (booking_id) REFERENCES bookings (id),
    CONSTRAINT fk_bank_transactions_assigned_by FOREIGN KEY (assigned_by) REFERENCES users (id),
    CONSTRAINT fk_bank_transactions_resolved_by FOREIGN KEY (resolved_by) REFERENCES users (id),
    CONSTRAINT ck_bank_transactions_sepay_id CHECK (sepay_id >= 0),
    CONSTRAINT ck_bank_transactions_amount CHECK (amount > 0),
    CONSTRAINT ck_bank_transactions_applied CHECK (applied_amount >= 0 AND applied_amount <= amount),
    CONSTRAINT ck_bank_transactions_outcome CHECK (
        outcome IN ('APPLIED', 'OVERPAID', 'NOT_PAYABLE', 'UNMATCHED', 'WRONG_ACCOUNT')),
    -- Có đơn khi và chỉ khi kết quả là đã gắn vào đơn.
    CONSTRAINT ck_bank_transactions_booking CHECK (
        (booking_id IS NULL) = (outcome IN ('UNMATCHED', 'WRONG_ACCOUNT'))),
    CONSTRAINT ck_bank_transactions_assignment CHECK ((assigned_by IS NULL) = (assigned_at IS NULL)),
    CONSTRAINT ck_bank_transactions_resolution CHECK (
        (resolved_by IS NULL) = (resolved_at IS NULL) AND (resolved_at IS NULL) = (resolution_note IS NULL))
);

-- Giao dịch của một đơn (trang chi tiết đơn ở admin).
CREATE INDEX idx_bank_transactions_booking ON bank_transactions (booking_id);
-- Danh sách giao dịch, mới nhất trước.
CREATE INDEX idx_bank_transactions_received ON bank_transactions (received_at DESC, id DESC);
