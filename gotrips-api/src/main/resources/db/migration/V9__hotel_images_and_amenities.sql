-- Ảnh khách sạn, ảnh loại phòng và danh mục tiện ích chuẩn.
--
-- Ảnh đại diện vẫn là hotels.image_url / image_alt: thẻ, kết quả tìm, trang đặt phòng và đơn đã đọc hai cột này.
-- hotel_images chỉ là bộ ảnh XEM THÊM ở trang chi tiết nên không lặp lại ảnh đại diện và được phép rỗng. Không có
-- bảng ảnh "phòng": DB không quản lý phòng vật lý, ảnh gắn với loại phòng (hotel_room_type_images).
--
-- Tiện ích trước đây là hotels.amenities text[] gõ tự do (mỗi nơi viết một kiểu, không gắn được cho loại phòng). Nay là
-- danh mục dùng chung, định danh bằng `code`. DB không lưu tên icon: icon là chuyện của giao diện, web tự ánh xạ từ code.
-- KHÔNG chuyển dữ liệu cũ bằng SQL: chuỗi tự do không ánh xạ chắc chắn được, và dữ liệu khách sạn chỉ đến từ seed
-- (chưa có API quản trị khách sạn) nên seed nạp lại bằng bảng mới.

CREATE TABLE amenities (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       varchar(50)  NOT NULL,
    name       varchar(100) NOT NULL,
    -- Gắn được cho khách sạn, cho loại phòng, hay cả hai. Khoá ngoại ở bảng nối không ép được luật này: dữ liệu
    -- phải tự tuân thủ (SeedDataTests canh seed).
    scope      varchar(10)  NOT NULL,
    sort_order integer      NOT NULL DEFAULT 0,
    CONSTRAINT uq_amenities_code UNIQUE (code),
    CONSTRAINT ck_amenities_code_format CHECK (code ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT ck_amenities_scope CHECK (scope IN ('HOTEL', 'ROOM', 'BOTH'))
);

-- Xoá khách sạn / loại phòng thì dòng nối đi theo. Khoá ngoại tới amenities CỐ Ý không cascade: tiện ích đang được
-- dùng thì không xoá được, nếu không nó biến mất khỏi mọi nơi mà không ai biết.
CREATE TABLE hotel_amenities (
    hotel_id   bigint NOT NULL,
    amenity_id bigint NOT NULL,
    CONSTRAINT pk_hotel_amenities PRIMARY KEY (hotel_id, amenity_id),
    CONSTRAINT fk_hotel_amenities_hotel FOREIGN KEY (hotel_id) REFERENCES hotels (id) ON DELETE CASCADE,
    CONSTRAINT fk_hotel_amenities_amenity FOREIGN KEY (amenity_id) REFERENCES amenities (id)
);

CREATE INDEX idx_hotel_amenities_amenity_id ON hotel_amenities (amenity_id);

CREATE TABLE hotel_room_type_amenities (
    room_type_id bigint NOT NULL,
    amenity_id   bigint NOT NULL,
    CONSTRAINT pk_hotel_room_type_amenities PRIMARY KEY (room_type_id, amenity_id),
    CONSTRAINT fk_hotel_room_type_amenities_room_type FOREIGN KEY (room_type_id)
        REFERENCES hotel_room_types (id) ON DELETE CASCADE,
    CONSTRAINT fk_hotel_room_type_amenities_amenity FOREIGN KEY (amenity_id) REFERENCES amenities (id)
);

CREATE INDEX idx_hotel_room_type_amenities_amenity_id ON hotel_room_type_amenities (amenity_id);

-- UNIQUE (chủ, sort_order) giữ thứ tự ảnh không mơ hồ, đồng thời là index khi đọc ảnh theo chủ.
CREATE TABLE hotel_images (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id   bigint       NOT NULL,
    image_url  varchar(500) NOT NULL,
    image_alt  varchar(255) NOT NULL,
    sort_order integer      NOT NULL,
    CONSTRAINT fk_hotel_images_hotel FOREIGN KEY (hotel_id) REFERENCES hotels (id) ON DELETE CASCADE,
    CONSTRAINT uq_hotel_images_hotel_sort_order UNIQUE (hotel_id, sort_order),
    CONSTRAINT ck_hotel_images_sort_order CHECK (sort_order >= 0)
);

CREATE TABLE hotel_room_type_images (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_type_id bigint       NOT NULL,
    image_url    varchar(500) NOT NULL,
    image_alt    varchar(255) NOT NULL,
    sort_order   integer      NOT NULL,
    CONSTRAINT fk_hotel_room_type_images_room_type FOREIGN KEY (room_type_id)
        REFERENCES hotel_room_types (id) ON DELETE CASCADE,
    CONSTRAINT uq_hotel_room_type_images_room_type_sort_order UNIQUE (room_type_id, sort_order),
    CONSTRAINT ck_hotel_room_type_images_sort_order CHECK (sort_order >= 0)
);

ALTER TABLE hotels DROP COLUMN amenities;
