-- Vé máy bay: hãng bay và lịch bay. Lịch bay chạy MỖI NGÀY cùng giờ, nên một chuyến bay cụ thể = lịch bay + ngày bay
-- (không có bảng "chuyến bay theo ngày"). Ghế đã bán không lưu ở đây mà đếm từ đơn đặt vé (V5).

CREATE TABLE airlines (
    -- Mã 2 ký tự, cũng là tiền tố số hiệu chuyến bay.
    code varchar(2)   PRIMARY KEY,
    name varchar(100) NOT NULL,
    CONSTRAINT ck_airlines_code_format CHECK (code ~ '^[A-Z0-9]{2}$')
);

CREATE TABLE flight_schedules (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    airline_code          varchar(2)  NOT NULL,
    flight_number         varchar(10) NOT NULL,
    from_code             varchar(3)  NOT NULL,
    to_code               varchar(3)  NOT NULL,
    -- Giờ cất cánh theo giờ địa phương.
    depart_time           time        NOT NULL,
    duration_minutes      integer     NOT NULL,
    -- Giá hạng Phổ thông cho MỘT người lớn, đã gồm thuế phí, VND. Giá hạng khác, trẻ em và em bé tính từ giá này.
    economy_fare          bigint      NOT NULL,
    -- Số ghế bán được của MỖI ngày bay, theo từng hạng ghế. Em bé ngồi cùng người lớn nên không chiếm ghế.
    economy_seats         integer     NOT NULL,
    premium_economy_seats integer     NOT NULL,
    business_seats        integer     NOT NULL,
    first_seats           integer     NOT NULL,
    CONSTRAINT uq_flight_schedules_number UNIQUE (flight_number),
    CONSTRAINT fk_flight_schedules_airline FOREIGN KEY (airline_code) REFERENCES airlines (code),
    CONSTRAINT fk_flight_schedules_from FOREIGN KEY (from_code) REFERENCES airports (code),
    CONSTRAINT fk_flight_schedules_to FOREIGN KEY (to_code) REFERENCES airports (code),
    CONSTRAINT ck_flight_schedules_distinct CHECK (from_code <> to_code),
    -- Giờ hạ cánh chỉ hỗ trợ "+1 ngày" nên thời gian bay phải dưới 24 giờ.
    CONSTRAINT ck_flight_schedules_duration CHECK (duration_minutes > 0 AND duration_minutes < 1440),
    CONSTRAINT ck_flight_schedules_fare CHECK (economy_fare > 0),
    CONSTRAINT ck_flight_schedules_seats CHECK (
        economy_seats >= 0 AND premium_economy_seats >= 0 AND business_seats >= 0 AND first_seats >= 0)
);

CREATE INDEX idx_flight_schedules_route ON flight_schedules (from_code, to_code, depart_time);
